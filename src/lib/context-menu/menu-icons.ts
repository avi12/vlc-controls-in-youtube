export function createMenuIcon(row: MenuRow) {
  const elIcon = document.createElementNS(SVG_NAMESPACE, "svg");
  elIcon.setAttribute("height", ICON_SIZE);
  elIcon.setAttribute("width", ICON_SIZE);
  elIcon.setAttribute("viewBox", ICON_VIEW_BOX);
  elIcon.setAttribute("fill", "none");
  for (const pathData of ICON_PATHS[row]) {
    const elPath = document.createElementNS(SVG_NAMESPACE, "path");
    elPath.setAttribute("d", pathData);
    elPath.setAttribute("fill", ICON_FILL);
    elIcon.append(elPath);
  }
  return elIcon;
}
